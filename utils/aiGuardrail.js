// utils/aiGuardrail.js
const { trace } = require('@opentelemetry/api');

function generateFlagDiff(currentFlagState, aiCommand) {
  const span = trace.getActiveSpan();

  if (!aiCommand || typeof aiCommand !== 'object' || !aiCommand.flagKey) {
    if (span) span.setAttribute('ai.guardrail.status', 'rejected_invalid_schema');
    return {
      valid: false,
      error: 'Invalid or incomplete flag command generated by AI Copilot.'
    };
  }

  if (
    aiCommand.rollout !== undefined &&
    (typeof aiCommand.rollout !== 'number' || aiCommand.rollout < 0 || aiCommand.rollout > 100)
  ) {
    if (span) span.setAttribute('ai.guardrail.status', 'rejected_out_of_bounds');
    return {
      valid: false,
      error: 'Rollout percentage must be between 0 and 100.'
    };
  }

  const proposedEnabled =
    aiCommand.enabled !== undefined ? Boolean(aiCommand.enabled) : currentFlagState.enabled;
  const proposedRollout =
    aiCommand.rollout !== undefined ? aiCommand.rollout : currentFlagState.rollout;

  if (span) {
    span.setAttribute('ai.guardrail.status', 'pending_human_approval');
    span.setAttribute('ld.flag.key', String(aiCommand.flagKey));
    span.setAttribute('ai.proposed.enabled', proposedEnabled);
  }

  return {
    valid: true,
    preview: {
      flagKey: String(aiCommand.flagKey),
      before: {
        enabled: Boolean(currentFlagState.enabled),
        rollout: currentFlagState.rollout ?? 0
      },
      after: {
        enabled: proposedEnabled,
        rollout: proposedRollout
      },
      reason: aiCommand.reason || 'Remediation / rollout requested via AI Copilot'
    },
    executableCommand: {
      flagKey: String(aiCommand.flagKey),
      enabled: proposedEnabled,
      rollout: proposedRollout,
      reason: aiCommand.reason || 'Remediation / rollout requested via AI Copilot'
    }
  };
}

module.exports = { generateFlagDiff };